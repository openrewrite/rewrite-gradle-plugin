/**
 * Writes the plugin reference to the output file, or with `--check` fails when the file is out of date.
 *
 * Usage: `<plugin source root> <output file> [--check]`
 */
fun main(args: Array<String>) {
    val output = File(args[1])
    val reference = PluginReference(File(args[0])).render()
    if ("--check" !in args) {
        output.writeText(reference)
    } else if (!output.isFile || output.readText() != reference) {
        System.err.println("$output is out of date. Run ./gradlew :plugin:generatePluginReference and commit the result.")
        exitProcess(1)
    }
}

private val userFacingFields = listOf(
    "activeRecipes",
    "activeStyles",
    "configFile",
    "checkstyleConfigFile",
    "enableExperimentalGradleBuildScriptParsing",
    "exportDatatables",
    "exclusions",
    "plainTextMasks",
    "sizeThresholdMb",
    "rewriteVersion",
    "logCompilationWarningsAndErrors",
    "failOnInvalidActiveRecipes",
    "failOnDryRunResults",
    "throwOnParseFailures",
    "pomCacheEnabled",
    "pomCacheDirectory",
)

private val userFacingMethods = listOf(
    "activeRecipe",
    "clearActiveRecipes",
    "activeStyle",
    "clearActiveStyles",
    "exclusion",
    "plainTextMask",
)

private val defaultsToSentence = Regex("""\s*Defaults to ((?:`[^`]*`|[^.`])*)\.""")

class PluginReference(private val sourceRoot: File) {
    private val plugin = JavaSource(sourceRoot.resolve("org/openrewrite/gradle/RewritePlugin.java"))
    private val extension = JavaSource(sourceRoot.resolve("org/openrewrite/gradle/RewriteExtension.java"))

    fun render(): String {
        val documented = extension.fields.filter { it.javadoc != null }.map { it.name } +
                extension.methods.filter { it.javadoc != null }.map { it.name }
        val undocumented = (userFacingFields + userFacingMethods).filter { it !in documented }
        check(undocumented.isEmpty()) { "RewriteExtension members are missing Javadoc: ${undocumented.joinToString()}" }

        val sections = mapOf(
            "tasks" to tasksTable(),
            "kotlinIsProperties" to kotlinIsProperties(),
            "properties" to propertiesTable(),
            "plainTextMasks" to plainTextMasks(),
            "methods" to methodsTable(),
        )
        val template = javaClass.getResource("/plugin-reference.template.md")!!.readText()
        return Regex("""\{\{(\w+)}}""").replace(template) { sections[it.groupValues[1]] ?: error("Unknown placeholder ${it.value}") } +
                "\n<!-- Generated by ./gradlew :plugin:generatePluginReference from plugin/src/pluginReference/resources/plugin-reference.template.md -->\n"
    }

    private fun tasksTable(): String {
        val rows = plugin.invocations("register").mapNotNull { register ->
            val name = (register.arguments.getOrNull(0) as? LiteralTree)?.value as? String
            val type = (register.arguments.getOrNull(1) as? MemberSelectTree)?.takeIf { it.identifier.contentEquals("class") }?.expression
            if (name == null || type == null) {
                return@mapNotNull null
            }
            val taskSource = JavaSource(sourceRoot.resolve("${plugin.packagePath}/$type.java"))
            val description = taskSource.invocations("setDescription").single().arguments.single() as LiteralTree
            listOf("`$name`", description.value as String)
        }
        return table(listOf("Task" to 1, "Description" to 3), rows)
    }

    private fun kotlinIsProperties(): String = extension.methods
        .filter { it.isPublic && it.name.startsWith("is") && it.returnType == "boolean" }
        .joinToString(", ") { "`${it.name}`" }

    private fun propertiesTable(): String {
        val rows = extension.fields.filter { it.name in userFacingFields }.map { field ->
            val javadoc = field.javadoc!!
            val default = if (field.name == "plainTextMasks") {
                // Absolute, as rewrite-docs copies this table into docs.openrewrite.org
                "[Built-in list](https://openrewrite.github.io/rewrite-gradle-plugin/#default-plain-text-masks)"
            } else {
                defaultsToSentence.find(javadoc)?.groupValues?.get(1) ?: inferredDefault(field)
            }
            listOf("`${field.name}`", "`${field.type}`", default, javadoc.replace(defaultsToSentence, "").trim())
        }
        return table(listOf("Property" to 4, "Type" to 2, "Default" to 2, "Description" to 6), rows)
    }

    private fun inferredDefault(field: JavaSource.Field): String = when (val initializer = field.initializer) {
        null -> if (field.type == "boolean") "`false`" else "`null`"
        is LiteralTree -> "`${initializer.value}`"
        is NewClassTree -> if (initializer.identifier.toString().startsWith("ArrayList")) "Empty list" else null
        else -> null
    } ?: error("Can't infer the default of ${field.name}; state it in a \"Defaults to\" sentence in its Javadoc")

    private fun plainTextMasks(): String = extension.stringLiterals(extension.methods.single { it.name == "getPlainTextMasks" }.tree)
        .joinToString(" ") { "`$it`" }

    private fun methodsTable(): String {
        val rows = extension.methods.filter { it.name in userFacingMethods && it.javadoc != null }.map { method ->
            val acceptsCollection = extension.methods.any { it.name == method.name && it.parameterTypes.singleOrNull()?.startsWith("Collection") == true }
            listOf(
                "`${method.name}(${method.parameterTypes.joinToString(", ")})`",
                method.javadoc + if (acceptsCollection) " Also accepts a `Collection<String>`." else "",
            )
        }
        return table(listOf("Method" to 1, "Description" to 3), rows)
    }

    // Column weights become the separator's dash counts, which pandoc uses as relative column widths
    private fun table(columns: List<Pair<String, Int>>, rows: List<List<String>>): String =
        (listOf(columns.map { it.first }, columns.map { "-".repeat(it.second * 4) }) + rows)
            .joinToString("\n") { cells -> cells.joinToString(" | ", "| ", " |") }
}

/**
 * A Java source file parsed, but not attributed, by the JDK compiler, so it needs nothing on the classpath.
 */
class JavaSource(file: File) {
    class Field(val name: String, val type: String, val initializer: ExpressionTree?, val javadoc: String?)
    class Method(val name: String, val parameterTypes: List<String>, val returnType: String?, val isPublic: Boolean, val javadoc: String?, val tree: MethodTree)

    private val task = ToolProvider.getSystemJavaCompiler().let { compiler ->
        val fileManager = compiler.getStandardFileManager(null, null, null)
        compiler.getTask(null, fileManager, null, null, null, fileManager.getJavaFileObjects(file)) as JavacTask
    }
    private val unit: CompilationUnitTree = task.parse().single()
    private val docTrees = DocTrees.instance(task)
    private val members = (unit.typeDecls.single() as ClassTree).members

    val packagePath = unit.packageName.toString().replace('.', '/')

    val fields = members.filterIsInstance<VariableTree>().map {
        Field(it.name.toString(), it.type.toString(), it.initializer, javadoc(it))
    }

    val methods = members.filterIsInstance<MethodTree>().map { method ->
        Method(
            method.name.toString(),
            // Printing the parameter keeps varargs as `String...`, which its type tree would print as `String[]`
            method.parameters.map { it.toString().substringBeforeLast(' ') },
            method.returnType?.toString(),
            Modifier.PUBLIC in method.modifiers.flags,
            javadoc(method),
            method,
        )
    }

    fun invocations(methodName: String): List<MethodInvocationTree> {
        val found = mutableListOf<MethodInvocationTree>()
        object : TreeScanner<Void?, Void?>() {
            override fun visitMethodInvocation(node: MethodInvocationTree, p: Void?): Void? {
                val name = when (val select = node.methodSelect) {
                    is IdentifierTree -> select.name
                    is MemberSelectTree -> select.identifier
                    else -> null
                }
                if (name != null && name.contentEquals(methodName)) {
                    found += node
                }
                return super.visitMethodInvocation(node, p)
            }
        }.scan(unit, null)
        return found
    }

    fun stringLiterals(tree: Tree): List<String> {
        val found = mutableListOf<String>()
        object : TreeScanner<Void?, Void?>() {
            override fun visitLiteral(node: LiteralTree, p: Void?): Void? {
                (node.value as? String)?.let { found += it }
                return null
            }
        }.scan(tree, null)
        return found
    }

    private fun javadoc(member: Tree): String? = docTrees.getDocCommentTree(TreePath.getPath(unit, member))
        ?.fullBody
        ?.joinToString("") { it.toMarkdown() }
        ?.replace(Regex("""\s+"""), " ")
        ?.trim()

    private fun DocTree.toMarkdown(): String = when (this) {
        is TextTree -> body
        is DocLiteralTree -> if (kind == DocTree.Kind.CODE) "`${body.body}`" else body.body
        is LinkTree -> if (label.isEmpty()) "`${reference.signature.removePrefix("#")}`" else label.joinToString("") { it.toMarkdown() }
        is StartElementTree, is EndElementTree -> " "
        else -> error("Unsupported Javadoc in the plugin reference: $this")
    }
}
